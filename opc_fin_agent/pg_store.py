"""PostgreSQL 生产后端：sqlite3 API 兼容包装器，业务代码零改动切换。

设计要点（对应《阶段0技术规格-接口边界与数据分区设计》）：
- PgCompatConn 模拟 sqlite3.Connection 的最小 API（execute/commit/close），
  自动完成三件事：? → %s 占位符翻译、INSERT 追加 RETURNING id 映射 lastrowid、
  结果行字典化访问（兼容 sqlite3.Row 的 row["col"] 用法）。
- psycopg 惰性导入：未安装或连接失败时抛出带部署指引的 StorageNotConfigured，
  绝不静默降级、绝不编造连接（与 OCR/RAG 适配器同一诚实原则）。
- 本模块不承载敏感数据加密（字段加密在应用层），DSN 建议经环境变量注入。
"""
import os

PG_SCHEMA = """
CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no TEXT,
    content_hash TEXT UNIQUE,
    archive_path TEXT,
    payload TEXT,
    fields TEXT,
    grade TEXT,
    status TEXT DEFAULT 'pending',
    created_at TEXT
);
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id BIGINT,
    actor TEXT,
    action TEXT,
    detail TEXT,
    prev_hash TEXT,
    event_hash TEXT,
    created_at TEXT
);
CREATE TABLE IF NOT EXISTS pushed_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL,
    deadline TEXT NOT NULL,
    title TEXT,
    payload TEXT,
    mode TEXT,
    status TEXT,
    created_at TEXT,
    UNIQUE(task_id, deadline)
);
CREATE INDEX IF NOT EXISTS idx_documents_invoice_no ON documents(invoice_no);
CREATE INDEX IF NOT EXISTS idx_audit_doc_id ON audit_events(doc_id);
"""

INSTALL_HINT = (
    "PostgreSQL 驱动 psycopg 未安装。生产部署请在部署机执行："
    "pip install -r deploy/requirements-prod.txt（或 pip install 'psycopg[binary]'），"
    "详见 deploy/PG-MinIO部署指南.md。"
)


class StorageNotConfigured(RuntimeError):
    """存储后端未就绪：携带安装/部署指引，供上层诚实报错。"""


def translate_sql(sql):
    """sqlite 方言 → PG 方言：占位符翻译（纯函数，供单元测试）。"""
    return sql.replace("?", "%s")


def pg_driver_status():
    """探针：psycopg 是否已安装（供 meta 状态展示）。"""
    try:
        import psycopg  # noqa: F401
        return "installed"
    except ImportError:
        return "not_installed"


class _PgCursor:
    """包装 psycopg 游标，模拟 sqlite3.Cursor 的最小 API。"""

    def __init__(self, cursor, lastrowid=None):
        self._cur = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        row = self._cur.fetchone()
        return dict(row) if row is not None else None

    def fetchall(self):
        return [dict(r) for r in self._cur.fetchall()]


class PgCompatConn:
    """sqlite3 兼容连接：现有业务代码（?占位符/lastrowid/row["col"]）零改动运行于 PG。"""

    def __init__(self, dsn):
        dsn = dsn or os.environ.get("OPC_PG_DSN", "")
        if not dsn:
            raise StorageNotConfigured(
                "pg_dsn 未配置。请在 config/storage_config.json 填写连接串，"
                "或设置环境变量 OPC_PG_DSN（推荐，避免敏感信息落盘）。")
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as e:
            raise StorageNotConfigured(INSTALL_HINT) from e
        try:
            self._conn = psycopg.connect(dsn, row_factory=dict_row)
        except Exception as e:
            raise StorageNotConfigured(
                f"PostgreSQL 连接失败：{e}。请核对 DSN 与服务状态，"
                "部署步骤见 deploy/PG-MinIO部署指南.md。") from e
        self._ensure_schema()

    def _ensure_schema(self):
        cur = self._conn.cursor()
        # 按分号切分逐条执行（psycopg 扩展协议不支持多语句一次执行）
        for stmt in PG_SCHEMA.split(";"):
            stmt = stmt.strip()
            if stmt:
                cur.execute(stmt)
        self._conn.commit()

    def execute(self, sql, params=None):
        sql2 = translate_sql(sql)
        is_insert = sql2.lstrip().upper().startswith("INSERT")
        if is_insert and "RETURNING" not in sql2.upper():
            sql2 = sql2.rstrip().rstrip(";") + " RETURNING id"
        cur = self._conn.cursor()
        cur.execute(sql2, params)
        lastrowid = None
        if is_insert and "RETURNING" in sql2.upper():
            row = cur.fetchone()
            if row:
                lastrowid = row.get("id")
        return _PgCursor(cur, lastrowid)

    def executescript(self, script):  # sqlite3 API 兼容
        cur = self._conn.cursor()
        for stmt in script.split(";"):
            stmt = stmt.strip()
            if stmt:
                cur.execute(stmt)
        self._conn.commit()

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        try:
            self._conn.close()
        except Exception:
            pass
